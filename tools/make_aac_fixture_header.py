#!/usr/bin/env python3
"""Write audiohelper/AACSelfTestFixture.h from tests/fixtures/aac_latm_48k_stereo.loas.

The header is committed so the production build needs no generation step; tests/test_aac.py fails if it ever
drifts from the fixture. Run this after changing the fixture:  python3 tools/make_aac_fixture_header.py
"""
import pathlib
import struct
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]


def render():
    loas = (ROOT / "tests/fixtures/aac_latm_48k_stereo.loas").read_bytes()
    aus = (ROOT / "tests/fixtures/aac_latm_48k_stereo.aus").read_bytes()
    count = struct.unpack_from("<I", aus, 0)[0]
    lines = [
        "/* Generated by tools/make_aac_fixture_header.py from tests/fixtures/aac_latm_48k_stereo.loas: ffmpeg's",
        " * AAC-LC 48 kHz stereo encode of a 0.5 s 440 Hz tone, as LOAS-framed LATM. Do not edit by hand. */",
        "#pragma once",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        f"static const unsigned g_selftest_expected_elements = {count}u;",
        f"static const size_t g_selftest_latm_len = {len(loas)}u;",
        "static const uint8_t g_selftest_latm[] = {",
    ]
    for i in range(0, len(loas), 16):
        lines.append("    " + ", ".join("0x%02x" % b for b in loas[i:i + 16]) + ",")
    lines += ["};", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    out = ROOT / "audiohelper/AACSelfTestFixture.h"
    out.write_text(render())
    print(f"wrote {out.relative_to(ROOT)}", file=sys.stderr)

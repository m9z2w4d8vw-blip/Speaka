#!/usr/bin/env python3
"""Embed the ffmpeg LATM fixture into fixture_data.h so the on-device test needs no pushed files.

Reads tests/fixtures/aac_latm_48k_stereo.loas (the LOAS/LATM stream) and .aus (the matching access-unit count),
writes tools/aac_decode_test/fixture_data.h with the raw bytes and the expected AudioMuxElement count.
"""
import pathlib
import struct
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
loas = (ROOT / "tests/fixtures/aac_latm_48k_stereo.loas").read_bytes()
aus = (ROOT / "tests/fixtures/aac_latm_48k_stereo.aus").read_bytes()
au_count = struct.unpack_from("<I", aus, 0)[0]

out = ROOT / "tools/aac_decode_test/fixture_data.h"
lines = [
    "/* Generated by make_fixture_header.py from tests/fixtures/aac_latm_48k_stereo.*. Do not edit by hand. */",
    "#pragma once",
    "#include <stddef.h>",
    "#include <stdint.h>",
    "",
    f"static const unsigned g_expected_au_count = {au_count}u;",
    f"static const size_t g_latm_loas_len = {len(loas)}u;",
    "static const uint8_t g_latm_loas[] = {",
]
for i in range(0, len(loas), 16):
    chunk = ", ".join("0x%02x" % b for b in loas[i:i + 16])
    lines.append("    " + chunk + ",")
lines.append("};")
lines.append("")
out.write_text("\n".join(lines) + "\n")
print(f"wrote {out} ({len(loas)} LATM bytes, {au_count} expected access units)", file=sys.stderr)
